def _nutation_args(jde):
    t = (jde - J2000) / 36525.0
    l = (134.96298139 + 477198.867398 * t + 0.008697221 * t * t
         + t ** 3 / 56250.0) * _DEG          # 月球平近点角
    lp = (357.52772333 + 35999.050340 * t - 0.000160279 * t * t
          - t ** 3 / 30000.0 + t ** 4 / 47000.0) * _DEG   # 太阳平近点角
    f = (93.27191028 + 483202.017538 * t - 0.003682502 * t * t
         + t ** 3 / 327270.0) * _DEG          # 月球升交点平角距
    d = (297.85036306 + 445267.111480 * t - 0.001914220 * t * t
         + t ** 3 / 189474.0) * _DEG          # 日月平角距
    om = (125.04452222 - 1934.136261 * t + 0.002070833 * t * t
          + t ** 3 / 450000.0) * _DEG         # 月球升交点平黄经
    return l, lp, f, d, om, t


def nutation(jde):
    """黄经章动 Δψ 与交角章动 Δε（单位：角秒）。"""
    l, lp, f, d, om, t = _nutation_args(jde)
    dpsi = 0.0
    deps = 0.0
    for (cl, clp, cf, cd, com, p, pt, e, et) in _NUT_TERMS:
        arg = cl * l + clp * lp + cf * f + cd * d + com * om
        dpsi += (p + pt * t) * math.sin(arg)
        deps += (e + et * t) * math.cos(arg)
    return dpsi / 10000.0, deps / 10000.0


def mean_obliquity(jde):
    """平黄赤交角（度）。"""
    t = (jde - J2000) / 36525.0
    return (23.0 + 26.0 / 60.0 + 21.448 / 3600.0
            - (46.8150 * t + 0.00059 * t * t - 0.001813 * t * t * t) / 3600.0)


def sun_apparent_longitude(jde):
    """太阳视黄经（度，0–360，动力学时 JDE）。"""
    tau = (jde - J2000) / 365250.0
    lon = math.degrees(_eval_series(_L_TERMS, tau)) + 180.0
    r = _eval_series(_R_TERMS, tau)
    lon += -0.09033 / 3600.0               # VSOP87 -> FK5
    lon += -20.4898 / (3600.0 * r)         # 周年光行差
    lon += nutation(jde)[0] / 3600.0       # 章动
    return lon % 360.0


def sun_apparent_ra(jde):
    """太阳视赤经（度）。"""
    lon = sun_apparent_longitude(jde) * _DEG
    dpsi, deps = nutation(jde)
    eps = (mean_obliquity(jde) + deps / 3600.0) * _DEG
    ra = math.atan2(math.cos(eps) * math.sin(lon), math.cos(lon))
    return math.degrees(ra) % 360.0


def equation_of_time(jde):
    """均时差 E = 真太阳时 − 平太阳时（秒）。"""
    t = (jde - J2000) / 36525.0
    l0 = (280.4664567 + 36000.76982779 * t + 0.0003032028 * t * t
          + t ** 3 / 49931.0 - t ** 4 / 15300.0 - t ** 5 / 2000000.0)
    dpsi = nutation(jde)[0]
    deps = nutation(jde)[1]
    eps = (mean_obliquity(jde) + deps / 3600.0) * _DEG
    e = l0 - 0.0057183 - sun_apparent_ra(jde) + dpsi * math.cos(eps) / 3600.0
    e = (e + 180.0) % 360.0 - 180.0
    return e * 240.0


def _norm180(x):
    x = x % 360.0
    return x - 360.0 if x > 180.0 else x


def _solve_sun_longitude(target, jde_guess):
    """求太阳视黄经等于 target 的动力学时 JDE（牛顿迭代）。"""
    jde = jde_guess
    for _ in range(30):
        diff = _norm180(target - sun_apparent_longitude(jde))
        step = diff / TROPICAL_YEAR_DEG_PER_DAY
        jde += step
        if abs(step) < 1e-8:
            break
    return jde


def _tt_to_beijing_jd(jde):
    year = 2000.0 + (jde - J2000) / 365.25
    return jde - delta_t_seconds(year) / 86400.0 + 8.0 / 24.0


def _date_to_jde(d):
    """北京时 date 的 0 时 -> 近似 JDE（用于迭代初值）。"""
    return julian_day(d.year, d.month, d.day) - 8.0 / 24.0 + 0.0002



