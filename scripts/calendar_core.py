def true_solar_time(dt, longitude, standard_meridian=STANDARD_MERIDIAN_CN):
    """真太阳时。返回 (真太阳时 datetime, 修正秒数)。

    修正秒数 = 经度时差 (longitude − standard_meridian)×240 s/° + 均时差。
    dt 视为「标准时区墙钟时间」（中国＝北京时间 UTC+8），longitude 东经为正。
    境外使用时把 standard_meridian 换成该时区标准经线（如纽约 −75）。
    """
    if standard_meridian is None:
        standard_meridian = STANDARD_MERIDIAN_CN
    if not (-180.0 <= float(longitude) <= 180.0):
        raise DateError("经度越界：%r" % (longitude,))
    dt = _as_datetime(dt)
    _check_year(dt.year)
    # 标准时墙钟 -> UT -> TT
    ut = dt - timedelta(hours=8.0)
    jd_ut = julian_day(ut.year, ut.month, ut.day, ut.hour, ut.minute + ut.second / 60.0)
    jde = jd_ut + delta_t_seconds(ut.year) / 86400.0
    lon_seconds = (float(longitude) - float(standard_meridian)) * 240.0
    eot = equation_of_time(jde)
    total = lon_seconds + eot
    return (dt + timedelta(seconds=total), int(round(total)))


