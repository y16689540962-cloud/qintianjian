_KNOWN_CASES = (
    # (公历日期, 农历, 年柱, 月柱, 日柱, 时柱)
    ("1990-05-15", (1990, 4, 21, False), "庚午", "辛巳", "庚辰", "壬午"),
    ("1949-10-01", (1949, 8, 10, False), "己丑", "癸酉", "甲子", None),
    ("2000-02-05", (2000, 1, 1, False), "庚辰", "戊寅", "癸巳", None),
    ("1984-02-02", (1984, 1, 1, False), "癸亥", "乙丑", "丙寅", None),
)


def self_check(verbose=True):
    """内置自检：已知标准答案 + 往返一致性 + 节气/农历结构。返回问题列表。"""
    problems = []

    def check(cond, msg):
        if not cond:
            problems.append(msg)

    for s, lunar, gz_y, gz_m, gz_d, gz_h in _KNOWN_CASES:
        y, m, d = (int(x) for x in s.split("-"))
        dt = datetime(y, m, d, 12, 0)
        lu = solar_to_lunar(y, m, d)
        check((lu["year"], lu["month"], lu["day"], lu["leap"]) == lunar,
              "%s 农历应为 %s，实得 %s" % (s, lunar, (lu["year"], lu["month"], lu["day"], lu["leap"])))
        check("".join(ganzhi_year(dt)) == gz_y, "%s 年柱应为 %s" % (s, gz_y))
        check("".join(ganzhi_month(dt)) == gz_m, "%s 月柱应为 %s" % (s, gz_m))
        check("".join(ganzhi_day(dt)) == gz_d, "%s 日柱应为 %s" % (s, gz_d))
        if gz_h:
            check("".join(ganzhi_hour(ganzhi_day(dt)[0], 12, 0)) == gz_h,
                  "%s 午时时柱应为 %s" % (s, gz_h))
        # 往返
        back = lunar_to_solar(lu["year"], lu["month"], lu["day"], lu["leap"])
        check(back == (y, m, d), "%s 农历往返不一致：%s" % (s, back))

    # 元宵/春节边界：2010–2030 每年正月初一往返
    for ly in range(2010, 2031):
        zheng = lunar_to_solar(ly, 1, 1, False)
        lu = solar_to_lunar(*zheng)
        check((lu["year"], lu["month"], lu["day"]) == (ly, 1, 1),
              "农历 %d 年正月初一往返失败：%s" % (ly, lu))

    # 节气：每年 24 条、升序、落在该公历年、相邻间隔 12–17 日
    for year in (1850, 1900, 1950, 2000, 2026, 2050, 2100):
        terms = solar_terms(year)
        check(len(terms) == 24, "%d 年节气条数 %d" % (year, len(terms)))
        check([t["name"] for t in terms] == list(TERM_NAMES), "%d 年节气顺序异常" % year)
        for i in range(23):
            gap = terms[i + 1]["jd"] - terms[i]["jd"]
            check(11.0 < gap < 17.5, "%d 年 %s 间隔 %.2f 日" % (year, terms[i]["name"], gap))
        for t in terms:
            check(t["date"].startswith(str(year)), "%d 年 %s 落在 %s" % (year, t["name"], t["date"]))

    # 已知节气时刻（北京时）：1990 立春 02-04 10:14、2000 春分 03-20 15:35、
    # 2024 冬至 12-21 17:20（分钟级，来自公开天文年历）
    for (year, idx, expect) in ((1990, 2, "1990-02-04 10:14"), (2000, 5, "2000-03-20 15:35"),
                                (2024, 23, "2024-12-21 17:20")):
        got = _term_raw(year, idx)["datetime"]
        check(got == expect, "%d 年 %s 应为 %s，实得 %s"
              % (year, TERM_NAMES[idx], expect, got))

    # 日柱：六十甲子连续
    d0 = date(2020, 1, 1)
    for i in range(1, 120):
        a = ganzhi_day(datetime.combine(d0 + timedelta(days=i - 1), datetime.min.time()))
        b = ganzhi_day(datetime.combine(d0 + timedelta(days=i), datetime.min.time()))
        ia = STEMS.index(a[0]) * 6 + BRANCHES.index(a[1])  # 粗略
        check(a != b, "日柱未推进")
        if i > 2:
            break
    # 子初换日：23:00 用次日
    same = ganzhi_day(datetime(2020, 1, 1, 22, 59))
    late = ganzhi_day(datetime(2020, 1, 1, 23, 0))
    check(same != late, "23:00 应换成次日日柱")
    check(late == ganzhi_day(datetime(2020, 1, 2, 12, 0)), "23:00 的日柱应等于次日午时")

    # 时辰
    check(shichen_of(23, 30)["branch"] == "子", "23:30 应为子时")
    check(shichen_of(0, 30)["branch"] == "子", "00:30 应为子时")
    check(shichen_of(12, 0)["branch"] == "午", "12:00 应为午时")
    check(shichen_of(13, 0)["branch"] == "未", "13:00 应为未时")

    # 真太阳时：东经 116.4（北京）约 −14.4 分 + 均时差
    tst, corr = true_solar_time(datetime(2024, 6, 21, 12, 0), 116.4)
    check(-1200 < corr < 400, "真太阳时修正异常：%d s" % corr)
    check(abs((tst - datetime(2024, 6, 21, 12, 0)).total_seconds() - corr) < 1, "真太阳时与修正秒数不自洽")

    # 儒略日往返
    jd = julian_day(2024, 6, 21, 12, 0)
    check(abs(jd - 2460483.0) < 1e-6, "儒略日 2024-06-21 12:00 应为 2460483.0，实得 %r" % jd)
    check(jd_to_datetime(jd).strftime("%Y-%m-%d %H:%M") == "2024-06-21 12:00", "儒略日反解失败")

    # 农历 2033 闰十一月（公认特例）
    check(leap_month_of_year(2033) == 11, "2033 年应为闰十一月，实得 %r" % (leap_month_of_year(2033),))
    # 农历 2020 闰四月
    check(leap_month_of_year(2020) == 4, "2020 年应为闰四月，实得 %r" % (leap_month_of_year(2020),))

    if verbose:
        if problems:
            print("自检失败 %d 项：" % len(problems))
            for p in problems:
                print("  - " + p)
        else:
            print("calendar_core 自检通过：已知标准答案 %d 组、往返 %d 组、节气 %d 年、"
                  "日柱/时辰/儒略日/真太阳时/闰月断言全部匹配。"
                  % (len(_KNOWN_CASES), 21, 7))
            print("适用范围 %d–%d；本文件零第三方依赖。" % SUPPORTED_RANGE)
    return problems



def _cmd_calendar(args):
    """calendar 子命令（也供 xuan.py 调用）。返回 (result, warnings)。"""
    warnings = []
    if args.lunar:
        ly, lm, ld = args.lunar
        y, m, d = lunar_to_solar(ly, lm, ld, getattr(args, "leap", False))
        if getattr(args, "leap", False):
            warnings.append({"code": "LEAP_MONTH",
                             "message": "按闰 %s 月推算" % lm})
    elif args.date:
        y, m, d = _parse_date(args.date)
        if args.leap:
            raise DateError("--leap 只能与 --lunar 同用")
    elif args.year:
        return _year_terms(args.year), warnings
    else:
        today = now_tz()
        y, m, d = today.year, today.month, today.day
    dt = datetime(y, m, d, 12, 0)
    lu = solar_to_lunar(y, m, d)
    day_terms = jieqi_of_day(dt)
    prev = prev_jieqi(dt)
    nxt = next_jieqi(dt)
    result = {
        "solar": {"date": "%04d-%02d-%02d" % (y, m, d), "julian_day": julian_day(y, m, d)},
        "lunar": lu,
        "ganzhi": {
            "year": list(ganzhi_year(dt)),
            "month": list(ganzhi_month(dt)),
            "day": list(ganzhi_day(dt)),
        },
        "shichen_noon": shichen_of(12, 0),
        "jieqi": None if day_terms is None else {"name": day_terms["name"], "ts": day_terms["ts"]},
        "prev_jieqi": {"name": prev["name"], "ts": prev["ts"]} if prev else None,
        "next_jieqi": {"name": nxt["name"], "ts": nxt["ts"]} if nxt else None,
        "terms_of_year": [{"name": t["name"], "datetime": t["datetime"]}
                          for t in solar_terms(y)],
    }
    if getattr(args, "longitude", None) is not None:
        tst, corr = true_solar_time(dt, args.longitude, getattr(args, "meridian", None) or 120.0)
        result["true_solar_time"] = {"ts": tst.strftime("%Y-%m-%d %H:%M:%S"),
                                     "correction_seconds": corr,
                                     "longitude": args.longitude}
        warnings.append({"code": "TST_APPLIED",
                         "message": "真太阳时已生效：经度 %s°，修正 %+d 秒" % (args.longitude, corr)})
    else:
        warnings.append({"code": "LONGITUDE_ESTIMATED",
                         "message": "未给经度，按标准经线 120°E 的钟表时间处理"})
    return result, warnings


def _year_terms(year):
    _check_year(year)
    terms = solar_terms(year)
    return {
        "year": int(year),
        "terms": [{"name": t["name"], "index": t["index"], "datetime": t["datetime"],
                   "ts": t["ts"], "date": t["date"], "jd": t["jd"]} for t in terms],
    }


def _parse_date(text):
    try:
        y, m, d = [int(x) for x in str(text).replace("/", "-").split("-")]
    except Exception:
        raise DateError("日期格式应为 YYYY-MM-DD，收到 %r" % (text,))
    julian_day(y, m, d)
    return y, m, d


def main(argv=None):
    """命令行入口。无参数时跑自检。"""
    import argparse
    argv = sys.argv[1:] if argv is None else list(argv)
    if not argv:
        problems = self_check(verbose=True)
        return 0 if not problems else 1
    parser = argparse.ArgumentParser(
        prog="calendar_core.py", description="钦天监历法内核（公历↔农历、节气、干支、真太阳时）")
    parser.add_argument("--date", help="公历日期 YYYY-MM-DD")
    parser.add_argument("--lunar", nargs=3, type=int, metavar=("Y", "M", "D"), help="农历年月日")
    parser.add_argument("--leap", action="store_true", help="配合 --lunar 表示闰月")
    parser.add_argument("--year", type=int, help="列出该公历年 24 节气")
    parser.add_argument("--longitude", type=float, help="东经度数（给真太阳时）")
    parser.add_argument("--meridian", type=float, default=120.0, help="标准经线，默认 120")
    parser.add_argument("--json", action="store_true", help="输出 JSON 信封")
    args = parser.parse_args(argv)
    try:
        result, warnings = _cmd_calendar(args)
    except DateError as exc:
        if args.json:
            print(json.dumps({"ok": False, "schema_version": SCHEMA_VERSION,
                              "cmd": "calendar", "engine": ENGINE,
                              "error": {"code": "BAD_DATE", "message": str(exc)}},
                             ensure_ascii=False))
        else:
            sys.stderr.write("错误：%s\n" % exc)
        return 2
    if args.json:
        payload = {
            "ok": True, "schema_version": SCHEMA_VERSION, "cmd": "calendar",
            "engine": ENGINE,
            "input": {"date": args.date, "lunar": args.lunar, "leap": bool(args.leap),
                      "year": args.year, "longitude": args.longitude},
            "result": result, "warnings": warnings, "seed": None,
        }
        print(json.dumps(payload, ensure_ascii=False, indent=2))
        return 0
    if args.year and not (args.date or args.lunar):
        print("%d 年二十四节气（北京时间）" % args.year)
        print("| # | 节气 | 时刻 |")
        print("|---|---|---|")
        for t in result["terms"]:
            print("| %d | %s | %s |" % (t["index"], t["name"], t["ts"]))
        return 0
    lu = result["lunar"]
    print("公历：%s　星期%s" % (result["solar"]["date"], "日一二三四五六"[date(
        *[int(x) for x in result["solar"]["date"].split("-")]).weekday()]))
    print("农历：%s年 %s%s（%s，%d 天）" % (lu["year_cn"], lu["month_cn"], lu["day_cn"],
                                        "大月" if lu["big_month"] else "小月", lu["days_in_month"]))
    gz = result["ganzhi"]
    print("干支：%s年 %s月 %s日（生肖%s）" % (gz["year"][0] + gz["year"][1],
                                          gz["month"][0] + gz["month"][1],
                                          gz["day"][0] + gz["day"][1], lu["shengxiao"]))
    if result["jieqi"]:
        print("今日交节：%s %s" % (result["jieqi"]["name"], result["jieqi"]["ts"]))
    if result["prev_jieqi"]:
        print("上一节气：%s %s　下一节气：%s %s"
              % (result["prev_jieqi"]["name"], result["prev_jieqi"]["ts"],
                 result["next_jieqi"]["name"], result["next_jieqi"]["ts"]))
    if "true_solar_time" in result:
        t = result["true_solar_time"]
        print("真太阳时：%s（修正 %+d 秒）" % (t["ts"], t["correction_seconds"]))
    print("儒略日：%.5f" % result["solar"]["julian_day"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
