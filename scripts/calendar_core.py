# 钟表时校正（1986–1991 中国夏令时）——全库共用，避免各模块各算各的
# ======================================================================
# 中国 1986–1991 年实行夏令时：起始日 02:00 → 03:00，结束日 02:00 拨回。
# 区间内的钟表读数比标准时快 1 小时，还原标准时需 −1 小时。
DST_WINDOWS = (
    (1986, 5, 4, 1986, 9, 14),
    (1987, 4, 12, 1987, 9, 13),
    (1988, 4, 10, 1988, 9, 11),
    (1989, 4, 16, 1989, 9, 17),
    (1990, 4, 15, 1990, 9, 16),
    (1991, 4, 14, 1991, 9, 15),
)


def dst_window_of(dt):
    """dt（钟表时）落在哪个夏令时区间；不在区间内返回 None。"""
    dt = _as_datetime(dt)
    for (y0, m0, d0, y1, m1, d1) in DST_WINDOWS:
        start = datetime(y0, m0, d0, 2, 0)
        end = datetime(y1, m1, d1, 2, 0)
        if start <= dt < end:
            return {"start": start.strftime("%Y-%m-%d %H:%M"),
                    "end": end.strftime("%Y-%m-%d %H:%M")}
    return None


def resolve_clock(dt, mode="fix"):
    """把钟表时还原成标准时，并给出 warnings 条目（供各模块直接并入信封）。

    mode:
      "fix"  —— 夏令时区间内自动 −1 小时（默认，最接近真实标准时）
      "warn" —— 不修正，只发 CLOCK_CHANGE 警告（与未做修正的模块保持口径一致）
      "off"  —— 完全不处理，不发警告
    返回 (标准时 datetime, [warning dict], meta dict|None)。
    """
    dt = _as_datetime(dt)
    if mode not in ("fix", "warn", "off"):
        raise DateError("resolve_clock 的 mode 只能是 fix/warn/off，收到 %r" % (mode,))
    if mode == "off":
        return dt, [], None
    win = dst_window_of(dt)
    if win is None:
        return dt, [], None
    if mode == "warn":
        return dt, [{"code": "CLOCK_CHANGE",
                     "message": "输入钟表时 %s 落在 1986–1991 中国夏令时区间（%s 至 %s），"
                                "本模块按原值计算未做 −1 小时修正；跨模块比较前务必统一时刻"
                                % (dt.strftime("%Y-%m-%d %H:%M"), win["start"], win["end"])}], None
    fixed = dt - timedelta(hours=1)
    meta = {"from": dt.strftime("%Y-%m-%d %H:%M"),
            "to": fixed.strftime("%Y-%m-%d %H:%M"),
            "reason": "1986–1991 中国夏令时", "window": win}
    return fixed, [{"code": "CLOCK_CHANGE",
                    "message": "1986–1991 中国夏令时：输入钟表时 %s 落在夏令时区间（%s 至 %s），"
                               "按 −1 小时还原为标准时 %s"
                               % (dt.strftime("%Y-%m-%d %H:%M"), win["start"], win["end"],
                                  fixed.strftime("%Y-%m-%d %H:%M"))}], meta


