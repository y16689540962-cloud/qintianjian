# 干支：年（立春界）、月（节界）、日（子初换日）、时（五鼠遁）
# ======================================================================
# 日柱基准：儒略日数 JDN 与六十甲子序的固定偏移，由已知日柱校准（见 __main__ 自检）。
# (JDN + 49) % 60 = 六十甲子序（甲子 = 0）。经 1949-10-01 甲子日、1990-05-15 庚辰日两点校准。
_DAY_CYCLE_OFFSET = 49


def _ganzhi_name(index):
    index %= 60
    return STEMS[index % 10], BRANCHES[index % 12]


def ganzhi_year(dt):
    """年柱（以立春交节时刻为界）。返回 (天干, 地支)。"""
    dt = _as_datetime(dt)
    _check_year(dt.year)
    lichun = _term_raw(dt.year, 2)["_dt"]
    gy = dt.year if dt >= lichun else dt.year - 1
    idx = (gy - 1984) % 60
    return _ganzhi_name(idx)


def ganzhi_month(dt):
    """月柱（以十二「节」为界）。返回 (天干, 地支)。"""
    dt = _as_datetime(dt)
    _check_year(dt.year)
    jie = jieqi_jie_of(dt)
    if jie is None:
        raise DateError("无法定位 %s 之前的节" % dt)
    n = ((jie["index"] - 2) % 24) // 2       # 立春=0(寅), 惊蛰=1(卯) …
    branch_index = (2 + n) % 12
    year_stem_index = STEMS.index(ganzhi_year(dt)[0])
    stem_index = (year_stem_index * 2 + 2 + n) % 10
    return STEMS[stem_index], BRANCHES[branch_index]


def ganzhi_day(dt):
    """日柱（以子初 23:00 换日）。返回 (天干, 地支)。"""
    dt = _as_datetime(dt)
    _check_year(dt.year)
    d = dt.date()
    if dt.hour >= 23:                        # 晚子时：已属次日
        d = d + timedelta(days=1)
    jdn = julian_day_number(d.year, d.month, d.day)
    return _ganzhi_name(jdn + _DAY_CYCLE_OFFSET)


def shichen_of(hour, minute=0):
    """时辰归属。返回 {"branch","index","range","hour","minute","late_zi"}。

    index 0 = 子（23:00–00:59）… 11 = 亥（21:00–22:59）。
    """
    hour = int(hour)
    minute = int(minute)
    if not (0 <= hour <= 23) or not (0 <= minute <= 59):
        raise DateError("时间越界：%02d:%02d" % (hour, minute))
    index = ((hour + 1) // 2) % 12
    start = (2 * index - 1) % 24
    end = (start + 1) % 24
    return {
        "branch": BRANCHES[index],
        "index": index,
        "range": "%02d:00-%02d:59" % (start, end),
        "hour": hour,
        "minute": minute,
        "late_zi": hour == 23,
        "early_zi": hour == 0,
    }


def ganzhi_hour(day_stem, hour, minute=0, late_zi="next_day"):
    """时柱（五鼠遁）。day_stem 为「已按口径确定的日干」四字之一。

    late_zi 只影响调用方传入哪个日干（本函数不再换日），此处保留参数以记录口径：
    - "next_day"（默认）：23:00–23:59 的日柱与日干用次日，子时干从次日日干起。
    - "same_day"：23:00–23:59 仍用当日日干。
    """
    if late_zi not in ("next_day", "same_day"):
        raise DateError("late_zi 只能是 next_day 或 same_day，收到 %r" % (late_zi,))
    if day_stem not in STEMS:
        raise DateError("日干非法：%r" % (day_stem,))
    sc = shichen_of(hour, minute)
    stem_index = (STEMS.index(day_stem) % 5 * 2 + sc["index"]) % 10
    return STEMS[stem_index], BRANCHES[sc["index"]]



