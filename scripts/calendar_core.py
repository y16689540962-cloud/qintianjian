def new_moon_jde(k):
    """第 k 个朔的动力学时 JDE（k=0 为 2000-01-06 的朔）。Meeus AA 第 49 章。"""
    k = int(k)
    t = k / 1236.85
    jde = (2451550.09766 + 29.530588861 * k + 0.00015437 * t ** 2
           - 0.000000150 * t ** 3 + 0.00000000073 * t ** 4)
    e = 1.0 - 0.002516 * t - 0.0000074 * t * t
    m = (2.5534 + 29.10535670 * k - 0.0000014 * t ** 2
         - 0.00000011 * t ** 3) * _DEG
    mp = (201.5643 + 385.81693528 * k + 0.0107582 * t ** 2
          + 0.00001238 * t ** 3 - 0.000000058 * t ** 4) * _DEG
    f = (160.7108 + 390.67050284 * k - 0.0016118 * t ** 2
         - 0.00000227 * t ** 3 + 0.000000011 * t ** 4) * _DEG
    om = (124.7746 - 1.56375588 * k + 0.0020672 * t ** 2
          + 0.00000215 * t ** 3) * _DEG
    jde += (-0.40720 * math.sin(mp)
            + 0.17241 * e * math.sin(m)
            + 0.01608 * math.sin(2 * mp)
            + 0.01039 * math.sin(2 * f)
            + 0.00739 * e * math.sin(mp - m)
            - 0.00514 * e * math.sin(mp + m)
            + 0.00208 * e * e * math.sin(2 * m)
            - 0.00111 * math.sin(mp - 2 * f)
            - 0.00057 * math.sin(mp + 2 * f)
            + 0.00056 * e * math.sin(2 * mp + m)
            - 0.00042 * math.sin(3 * mp)
            + 0.00042 * e * math.sin(m + 2 * f)
            + 0.00038 * e * math.sin(m - 2 * f)
            - 0.00024 * e * math.sin(2 * mp - m)
            - 0.00017 * math.sin(om)
            - 0.00007 * math.sin(mp + 2 * m)
            + 0.00004 * math.sin(2 * mp - 2 * f)
            + 0.00004 * math.sin(3 * m)
            + 0.00003 * math.sin(mp + m - 2 * f)
            + 0.00003 * math.sin(2 * mp + 2 * f)
            - 0.00003 * math.sin(mp + m + 2 * f)
            + 0.00003 * math.sin(mp - m + 2 * f)
            - 0.00002 * math.sin(mp - m - 2 * f)
            - 0.00002 * math.sin(3 * mp + m)
            + 0.00002 * math.sin(4 * mp))
    args = ((299.77 + 0.107408 * k - 0.009173 * t ** 2) * _DEG,
            (251.88 + 0.016321 * k) * _DEG,
            (251.83 + 26.651886 * k) * _DEG,
            (349.42 + 36.412478 * k) * _DEG,
            (84.66 + 18.206239 * k) * _DEG,
            (141.74 + 53.303771 * k) * _DEG,
            (207.14 + 2.453732 * k) * _DEG,
            (154.84 + 7.306860 * k) * _DEG,
            (34.52 + 27.261239 * k) * _DEG,
            (207.19 + 0.121824 * k) * _DEG,
            (291.34 + 1.844379 * k) * _DEG,
            (161.72 + 24.198154 * k) * _DEG,
            (239.56 + 25.513099 * k) * _DEG,
            (331.55 + 3.592518 * k) * _DEG)
    coeffs = (0.000325, 0.000165, 0.000164, 0.000126, 0.000110,
              0.000062, 0.000060, 0.000056, 0.000047, 0.000042,
              0.000040, 0.000037, 0.000035, 0.000023)
    for c, a in zip(coeffs, args):
        jde += c * math.sin(a)
    return jde


def _shuo_info(k):
    """第 k 个朔：(北京时 datetime, 该日 date)。"""
    hit = _SHINY_CACHE.get(k)
    if hit is None:
        dt = jd_to_datetime(_tt_to_beijing_jd(new_moon_jde(k)))
        hit = (dt, dt.date())
        _SHINY_CACHE[k] = hit
    return hit


def _k_approx(d):
    """给定北京时日期，估计其附近朔的 k。"""
    jd = julian_day(d.year, d.month, d.day)
    return int(math.floor((jd - 2451550.09766) / 29.530588861))


def _shuo_span(anchor):
    """覆盖 anchor 前后约 20 个月的朔列表 [(k, 北京时 datetime, date)]。"""
    k0 = _k_approx(anchor) - 2
    return [(k, _shuo_info(k)[0], _shuo_info(k)[1]) for k in range(k0, k0 + 20)]


_SUI_CACHE = {}


def _sui(lunar_year):
    """以「冬至」定岁：返回从 11 月（含冬至之月）到下一个 10 月的月份表。

    每项：{"year","month","leap","start","days","first_jd"}
    """
    lunar_year = int(lunar_year)
    hit = _SUI_CACHE.get(lunar_year)
    if hit is not None:
        return hit
    _check_year(lunar_year, _INTERNAL_MARGIN)
    dz_prev = _term_raw(lunar_year - 1, 23)["_dt"].date()
    dz_next = _term_raw(lunar_year, 23)["_dt"].date()
    shuo = _shuo_span(date(lunar_year - 1, 11, 15))
    days = [d for (_k, _dt, d) in shuo]
    instants = [dt for (_k, dt, _d) in shuo]
    i0 = None
    for i in range(len(days) - 1, -1, -1):
        if days[i] <= dz_prev:
            i0 = i
            break
    if i0 is None:
        raise DateError("无法定位 %d 年冬至所在月" % (lunar_year - 1))
    i1 = None
    for i in range(len(days) - 1, -1, -1):
        if days[i] <= dz_next:
            i1 = i
            break
    n = i1 - i0
    if not (11 <= n <= 14):
        raise DateError("岁长度异常（%d 个月），%d 年" % (n, lunar_year))
    zq = []
    for y in (lunar_year - 1, lunar_year):
        for idx in ZHONGQI_INDEX:
            zq.append(_term_raw(y, idx)["_dt"].date())
    zq.sort()
    months = []
    for j in range(n):
        start = days[i0 + j]
        end = days[i0 + j + 1] if j + 1 < n else days[i1]
        has_zq = any(start <= z < end for z in zq)
        months.append({"start": start, "end": end, "shuo": instants[i0 + j],
                       "days": (end - start).days, "has_zhongqi": has_zq})
    leap_index = None
    if n == 13:
        for j in range(1, n):
            if not months[j]["has_zhongqi"]:
                leap_index = j
                break
    num = 11
    prev_num = 11
    for j, m in enumerate(months):
        if j == 0:
            m["month"] = 11
            m["leap"] = False
        elif j == leap_index:
            m["month"] = prev_num
            m["leap"] = True
        else:
            num = num % 12 + 1
            m["month"] = num
            m["leap"] = False
        prev_num = m["month"]
        m["year"] = lunar_year - 1 if (j == 0 or (j == 1 and m["month"] == 12)) else lunar_year
    # 岁内 11、12 月归 lunar_year-1，其余（正月起）归 lunar_year
    for m in months:
        m["year"] = lunar_year - 1 if m["month"] in (11, 12) else lunar_year
    _SUI_CACHE[lunar_year] = months
    return months


def lunar_year_months(lunar_year):
    """农历某年（正月初一至除夕）的月份表，含闰月。"""
    lunar_year = int(lunar_year)
    sui = _sui(lunar_year)
    zheng = None
    for i, m in enumerate(sui):
        if m["month"] == 1 and not m["leap"]:
            zheng = i
            break
    if zheng is None:
        raise DateError("农历 %d 年缺正月" % lunar_year)
    months = [dict(m) for m in sui[zheng:]]
    for m in _sui(lunar_year + 1):
        if m["month"] == 1 and not m["leap"]:
            break
        months.append(dict(m))
    return months


def _year_cn(year):
    return "".join(YEAR_DIGIT_CN[int(c)] for c in str(int(year)))


def _month_cn(month, leap):
    return ("闰" if leap else "") + MONTH_CN[month - 1]


def _day_cn(day):
    if 1 <= day <= 10:
        return DAY_CN_1[day - 1]
    if 11 <= day <= 20:
        return DAY_CN_2[day - 11]
    if 21 <= day <= 30:
        return DAY_CN_3[day - 21]
    raise DateError("农历日越界：%d" % day)


def lunar_date_of(d):
    """公历 date -> (农历年, 月, 日, 是否闰月, 该月天数, 月首 date, 朔时刻 datetime)。"""
    d = _as_date(d)
    _check_year(d.year)
    for ly in (d.year - 1, d.year, d.year + 1):
        months = lunar_year_months(ly)
        if not months:
            continue
        first = months[0]["start"]
        last = months[-1]
        end = last["start"] + timedelta(days=last["days"])
        if first <= d < end:
            for m in months:
                mend = m["start"] + timedelta(days=m["days"])
                if m["start"] <= d < mend:
                    return (ly, m["month"], (d - m["start"]).days + 1, m["leap"],
                            m["days"], m["start"], m.get("shuo"))
    raise DateError("无法换算 %s 的农历日期" % d)


def solar_to_lunar(y, m=None, d=None):
    """公历 -> 农历。

    返回 {"year","month","day","leap","year_cn","month_cn","day_cn",
          "big_month","days_in_month","shengxiao","ganzhi_year"}。
    year/month/day 为公历；也可直接传 date/datetime。
    """
    if isinstance(y, (date, datetime)) and m is None and d is None:
        _d = _as_date(y)
        y, m, d = _d.year, _d.month, _d.day
    if m is None or d is None:
        raise DateError("solar_to_lunar 需要 (年, 月, 日)")
    y, m, d = int(y), int(m), int(d)
    julian_day(y, m, d)                       # 日期合法性校验
    ly, lm, ld, leap, days, start, shuo = lunar_date_of(date(y, m, d))
    gz = ganzhi_year(date(y, m, d))
    boundary = None
    if shuo is not None:
        minute_of_day = shuo.hour * 60 + shuo.minute + shuo.second / 60.0
        offset = minute_of_day if minute_of_day <= 720 else minute_of_day - 1440.0
        boundary = round(offset, 1)
    return {
        "year": ly,
        "month": lm,
        "day": ld,
        "leap": bool(leap),
        "year_cn": _year_cn(ly),
        "month_cn": _month_cn(lm, leap),
        "day_cn": _day_cn(ld),
        "big_month": days == 30,
        "days_in_month": days,
        "month_start": start.strftime("%Y-%m-%d"),
        "shuo": shuo.strftime("%Y-%m-%d %H:%M:%S") if shuo else None,
        "shuo_offset_minutes": boundary,
        "shuo_near_midnight": boundary is not None and abs(boundary) <= SHUO_BOUNDARY_MINUTES,
        "shengxiao": SHENGXIAO[(ly - 1984) % 12],
        "ganzhi_year": gz[0] + gz[1],
    }


def lunar_to_solar(ly, lm, ld, leap=False):
    """农历 -> 公历，返回 (年, 月, 日)。闰月由 leap=True 指定。"""
    ly, lm, ld = int(ly), int(lm), int(ld)
    if not (1 <= lm <= 12):
        raise DateError("农历月越界：%d" % lm)
    _check_year(ly)
    months = lunar_year_months(ly)
    target = None
    for m in months:
        if m["month"] == lm and bool(m["leap"]) == bool(leap):
            target = m
            break
    if target is None:
        raise DateError("农历 %d 年%s%d 月不存在" % (ly, "闰" if leap else "", lm))
    if not (1 <= ld <= target["days"]):
        raise DateError("农历 %d 年%s%d 月只有 %d 天，%d 日不存在"
                        % (ly, "闰" if leap else "", lm, target["days"], ld))
    out = target["start"] + timedelta(days=ld - 1)
    return (out.year, out.month, out.day)


def leap_month_of_year(lunar_year):
    """农历某年的闰月号；无闰返回 None。"""
    for m in lunar_year_months(lunar_year):
        if m["leap"]:
            return m["month"]
    return None



