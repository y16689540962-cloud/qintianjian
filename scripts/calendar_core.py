DELTA_T_QUADRATIC = 31.0        # s per (century)^2，潮汐减速长期项


def delta_t_seconds(year):
    """TT − UT1（秒）。超出 1850 下界按端点值取值（只作参考）。"""
    y = float(year)
    tab = DELTA_T_TABLE
    if y <= tab[0][0]:
        return tab[0][1]
    if y > DELTA_T_LAST_YEAR:
        u = (y - DELTA_T_LAST_YEAR) / 100.0
        return DELTA_T_LAST_VALUE + DELTA_T_QUADRATIC * u * u
    for i in range(len(tab) - 1):
        y0, t0 = tab[i]
        y1, t1 = tab[i + 1]
        if y0 <= y <= y1:
            return t0 + (t1 - t0) * (y - y0) / (y1 - y0)
    return DELTA_T_LAST_VALUE


def _eval_series(terms, tau):
    """按 T 的幂次求 VSOP87 级数（terms: ((幂次, 振幅A, 相位B, 频率C), ...)）。"""
    total = 0.0
    tpow = 1.0
    for power in range(0, 6):
        acc = 0.0
        for (p, a, b, c) in terms:
            if p == power:
                acc += a * math.cos(b + c * tau)
        if acc:
            total += acc * tpow
        tpow *= tau
    return total



