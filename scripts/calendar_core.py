def julian_day(y, m, d, hour=0.0, minute=0.0):
    """公历（格里历）年月日时分 -> 儒略日（float，含小数）。

    1850–2100 全在格里历内，故只实现格里历分支；1582-10-15 之前不适用。
    """
    y = int(y)
    m = int(m)
    d = int(d)
    if not (1 <= m <= 12):
        raise DateError("%d 月不存在" % m)
    if not (1 <= d <= _month_length(y, m)):
        raise DateError("%04d-%02d-%02d 不存在" % (y, m, d))
    a = (14 - m) // 12
    yy = y + 4800 - a
    mm = m + 12 * a - 3
    jdn = d + (153 * mm + 2) // 5 + 365 * yy + yy // 4 - yy // 100 + yy // 400 - 32045
    frac = (float(hour) * 3600.0 + float(minute) * 60.0) / 86400.0
    return jdn - 0.5 + frac


def julian_day_number(y, m, d):
    """公历日期 -> 儒略日数（整数，正午起算的 JDN）。"""
    return int(math.floor(julian_day(y, m, d) + 0.5))


def jd_to_datetime(jd):
    """儒略日（float）-> datetime（按同一时标解释，本库内一律为北京时）。"""
    jd = float(jd)
    jdn = int(math.floor(jd + 0.5))
    frac = jd + 0.5 - jdn
    micro = int(round(frac * 86400 * 1000000))
    if micro >= 86400 * 1000000:
        jdn += 1
        micro -= 86400 * 1000000
    # JDN -> 公历（格里历）
    a = jdn + 32044
    b = (4 * a + 3) // 146097
    c = a - (146097 * b) // 4
    dd = (4 * c + 3) // 1461
    e = c - (1461 * dd) // 4
    mm = (5 * e + 2) // 153
    day = e - (153 * mm + 2) // 5 + 1
    month = mm + 3 - 12 * (mm // 10)
    year = 100 * b + dd - 4800 + mm // 10
    return datetime(year, month, day) + timedelta(microseconds=micro)


def _month_length(y, m):
    if m == 2:
        leap = (y % 4 == 0 and y % 100 != 0) or (y % 400 == 0)
        return 29 if leap else 28
    return 30 if m in (4, 6, 9, 11) else 31


def _as_date(dt):
    if isinstance(dt, datetime):
        return dt.date()
    if isinstance(dt, date):
        return dt
    raise DateError("需要 datetime 或 date，收到 %r" % (dt,))


def _as_datetime(dt):
    if isinstance(dt, datetime):
        return dt
    if isinstance(dt, date):
        return datetime(dt.year, dt.month, dt.day)
    raise DateError("需要 datetime 或 date，收到 %r" % (dt,))


def now_tz(offset_hours=8.0):
    """当前「北京时间」（固定 UTC+8 偏移，不依赖 tzdata）。

    返回 naive datetime（墙钟时间），便于与用户输入的本地时间直接比较。
    """
    _off = timedelta(hours=float(offset_hours))
    return (datetime.now(timezone.utc).replace(tzinfo=None) + _off)



